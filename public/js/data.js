// Campaign queries. Every one runs as the signed-in user; RLS and grants decide
// what comes back, so a query for something you may not see returns nothing.
// No delete function exists on purpose (docs/adr/0004): removing a campaign
// would cascade to every character in it.
import { sb } from "./supabase-client.js";

// Everything the user can see is their own campaigns plus the ones they joined
// (two SELECT policies, unioned). invite_code is fetched separately and only for
// campaigns the user runs, so a player's view never carries it.
export async function listMyCampaigns(userId) {
  const [all, mine] = await Promise.all([
    sb.from("campaigns").select("id, name, dm_id, created_at").order("created_at", { ascending: true }),
    sb.from("campaigns").select("id, invite_code").eq("dm_id", userId),
  ]);
  if (all.error) throw all.error;
  if (mine.error) throw mine.error;
  const codes = new Map(mine.data.map((row) => [row.id, row.invite_code]));
  return all.data.map((c) => ({ ...c, isDm: c.dm_id === userId, inviteCode: codes.get(c.id) ?? null }));
}

// invite_code is generated by the database (migration 0002); the client never
// invents one.
export async function createCampaign(userId, name) {
  const { data, error } = await sb.from("campaigns").insert({ dm_id: userId, name }).select("id, name, dm_id");
  if (error) throw error;
  return data[0];
}

export async function joinCampaign(code) {
  const { data, error } = await sb.rpc("join_campaign", { p_invite_code: code });
  if (error) throw error;
  const row = Array.isArray(data) ? data[0] : data;
  if (!row) throw new Error("invalid invite code");
  return row; // { campaign_id, campaign_name }
}

// null when the campaign does not exist or the user may not see it.
export async function getCampaign(id) {
  const { data, error } = await sb.from("campaigns").select("id, name, dm_id").eq("id", id);
  if (error) throw error;
  return data[0] || null;
}

export async function getInviteCode(id) {
  const { data, error } = await sb.from("campaigns").select("invite_code").eq("id", id);
  if (error) throw error;
  return data[0] ? data[0].invite_code : null;
}
